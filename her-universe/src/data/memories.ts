// ----------------------------------------------------------------
// Dynamic memory generation for 1000+ photos
// Call generateMemoriesFromFileList() with your photo filenames
// ----------------------------------------------------------------

export function generateMemoriesFromFileList(
  filenames: string[],
  basePath = '/memories/'
): MemoryEntry[] {
  return filenames.map((filename, index) => {
    // Distribute photos evenly across sphere using Fibonacci sphere algorithm
    const goldenAngle = Math.PI * (3 - Math.sqrt(5)); // ~2.399 radians
    const y = 1 - (index / (filenames.length - 1)) * 2;   // -1 to 1
    const theta = goldenAngle * index;

    // Convert to spherical phi
    const phi = Math.acos(Math.max(-1, Math.min(1, y)));
    const normalizedTheta = ((theta % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI);

    return {
      id: `mem-${index.toString().padStart(4, '0')}`,
      imageUrl: `${basePath}${filename}`,
      title: `Memory #${index + 1}`,
      description: undefined,
      theta: normalizedTheta,
      phi,
    };
  });
}
