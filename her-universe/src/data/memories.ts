// For 1000+ photos: The photoSampler utility will dynamically
// generate MemoryEntry objects from the file list, assigning
// them spatial positions on the planet surface.
// ============================================================

export interface MemoryEntry {
  id: string;
  imageUrl: string;        // e.g. '/memories/photo-01.jpg'
  title: string;
  description?: string;

  // Spherical coordinates on planet surface (in radians)
  // theta: azimuthal angle [0, 2π]
  // phi: polar angle [0, π]  (0 = north pole, π = south pole)
  theta: number;
  phi: number;
}

